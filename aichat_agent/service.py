"""Persistent controller; each SDK execution has a killable process group."""
from __future__ import annotations

import argparse
import asyncio
import json
import os
from pathlib import Path
import signal
import sys
import uuid

from aichat.runtime import SDK_VERSION
from .gateway import Gateway, GatewayError

ROOT = Path(__file__).resolve().parent.parent


async def terminate_tree(proc):
    if proc is None:
        return
    try:
        os.killpg(proc.pid, signal.SIGTERM)
    except ProcessLookupError:
        return
    try:
        await asyncio.wait_for(proc.wait(), 1)
    except asyncio.TimeoutError:
        pass
    # Also kill a child that outlived its parent in the same process group.
    try:
        os.killpg(proc.pid, signal.SIGKILL)
    except ProcessLookupError:
        pass


def worker_environment(home: Path, cfg: dict) -> dict:
    # Do not forward the app credential, ambient cloud keys, proxy settings,
    # CLAUDECODE, plugins, or the user's actual HOME into the SDK execution.
    paths=[str(Path(sys.executable).parent),os.environ.get("PATH",""),"/usr/local/bin","/opt/homebrew/bin","/usr/bin","/bin"]
    return {"PATH": os.pathsep.join(paths),
            "PYTHONPATH": str(ROOT), "PYTHONUNBUFFERED": "1", "PYTHONIOENCODING": "utf-8",
            "HOME": str(home), "CLAUDE_CONFIG_DIR": str(home / ".claude"),
            "ANTHROPIC_API_KEY": cfg["api_key"],
            **({"ANTHROPIC_BASE_URL": cfg["base_url"]} if cfg.get("base_url") else {}),
            **({"AICHAT_CHROMIUM_PATH": os.environ["AICHAT_CHROMIUM_PATH"]} if os.environ.get("AICHAT_CHROMIUM_PATH") else {})}


class AgentService:
    def __init__(self, url: str, credential: str, state_dir: str | Path):
        self.url = url
        self.api = Gateway(url, credential)
        self.state_dir = Path(state_dir).resolve()
        self.state_dir.mkdir(parents=True, exist_ok=True, mode=0o700)
        self.owner = f"sdk-{os.getpid()}-{uuid.uuid4().hex[:8]}"
        self.jobs = set()
        self.stopping = False

    async def _renew(self, task_id, proof):
        # A cancelled task, changed configuration, revoked credential, or
        # invalid lease generation stops the current SDK process, not just SQL.
        while True:
            await asyncio.sleep(1)
            await self.api.call("POST", f"/api/agent/tasks/{task_id}/renew", proof=proof)

    async def execute(self, lease: dict):
        task, proof = lease["task"], lease["task_token"]
        tid = task["id"]
        process = None
        renewal = None
        err_reader = None
        try:
            state = await self.api.call("GET", f"/api/agent/tasks/{tid}/runtime", proof=proof)
            cfg, session = state["config"], state["session"]
            # The key is generated by the server; no model-supplied path.
            import hashlib
            identity = hashlib.sha256(session["session_key"].encode()).hexdigest()
            directory = self.state_dir / identity
            directory.mkdir(mode=0o700, parents=True, exist_ok=True)
            home = directory / "home"
            home.mkdir(mode=0o700, exist_ok=True)
            workspace = self.state_dir / 'workspaces' / f"room-{task.get('room_id',0)}"
            workspace.mkdir(mode=0o700,parents=True,exist_ok=True)
            sid = session.get("sdk_session_id")
            if sid and not any((home / ".claude" / "projects").glob(f"*/{sid}.jsonl")):
                await self.api.call("POST", f"/api/agent/tasks/{tid}/session-reset", proof=proof)
                session = {**session, "sdk_session_id": None, "total_cost": None, "usage_json": None}
            job = {"url": self.url, "task_token": proof, "profile": task["profile"], "config": cfg, "session": session, "sdk_version": SDK_VERSION, "controller_pid": os.getpid()}
            process = await asyncio.create_subprocess_exec(sys.executable, "-m", "aichat_agent.worker", cwd=workspace,
                       env=worker_environment(home, cfg), start_new_session=True,
                       stdin=asyncio.subprocess.PIPE, stdout=asyncio.subprocess.PIPE, stderr=asyncio.subprocess.PIPE,
                       limit=8 * 1024 * 1024)
            process.stdin.write((json.dumps(job, ensure_ascii=False) + "\n").encode())
            await process.stdin.drain()
            process.stdin.close()
            renewal = asyncio.create_task(self._renew(tid, proof))

            async def discard_stderr():
                # Drain to prevent subprocess deadlock; raw runtime output may
                # contain keys or internal prompts and is never sent to chat.
                while await process.stderr.read(8192):
                    pass
            err_reader = asyncio.create_task(discard_stderr())

            async def receive():
                result = None
                while line := await process.stdout.readline():
                    try:
                        msg = json.loads(line)
                    except (ValueError, UnicodeDecodeError):
                        continue
                    if msg.get("type") == "progress":
                        await self.api.call("POST", f"/api/agent/tasks/{tid}/progress", {"stage": msg["stage"]}, proof=proof)
                    elif msg.get('type')=='tool':
                        await self.api.call('POST',f'/api/agent/tasks/{tid}/tool-event',{'name':msg['name'],'id':msg.get('id','')},proof=proof)
                    elif msg.get("type") == "result":
                        result = msg["result"]
                    elif msg.get("type") == "error":
                        raise GatewayError(503, msg.get("code", "sdk_execution_failed"))
                await process.wait()
                if process.returncode or result is None:
                    raise GatewayError(503, "sdk_worker_failed")
                return result

            receiving = asyncio.create_task(receive())
            try:
                done, _ = await asyncio.wait([receiving, renewal], timeout=cfg["timeout_seconds"], return_when=asyncio.FIRST_COMPLETED)
                if renewal in done:
                    await renewal  # propagate invalid lease / revocation
                if receiving not in done:
                    raise GatewayError(504, "sdk_run_timeout")
                result = await receiving
            finally:
                if not receiving.done():
                    receiving.cancel()
                await asyncio.gather(receiving, return_exceptions=True)
            receipt = await self.api.call("POST", f"/api/agent/tasks/{tid}/result", {k: v for k, v in result.items() if k != "text"}, proof=proof)
            if result.get("outcome") not in ("completed", "no_model_needed", "recovered_without_model"):
                raise GatewayError(503, result.get("error_code") or "sdk_execution_failed")
            message_id = None
            task_api = Gateway(self.url, proof)
            try:
                if task["profile"] == "chat":
                    text = (receipt.get("reply_override") or result.get("text", "")).strip()
                    if not text:
                        raise GatewayError(503, "sdk_empty_reply")
                    response = await task_api.call("POST", "/api/tools/messages", {"body": text[:20000], "idempotency_key": f"task-{tid}"})
                    message_id = response["message"]["id"]
            finally:
                await task_api.close()
            await self.api.call("POST", f"/api/agent/tasks/{tid}/complete", {"result_message_id": message_id}, proof=proof)
        except asyncio.CancelledError:
            raise
        except Exception as e:
            code = e.code if isinstance(e, GatewayError) else "agent_service_error"
            # Lease errors are not reported through a newer worker's attempt.
            if code not in ("lease_not_held", "credential_revoked", "invalid_credential", "invalid_task_token", "agent_configuration_changed"):
                try:
                    await self.api.call("POST", f"/api/agent/tasks/{tid}/fail", {"error": code, "retry": code not in ("sdk_version_mismatch", "agent_not_configured", "delivery_missing")}, proof=proof)
                except Exception:
                    pass
        finally:
            if renewal:
                renewal.cancel()
                await asyncio.gather(renewal, return_exceptions=True)
            await terminate_tree(process)
            if err_reader:
                err_reader.cancel()
                await asyncio.gather(err_reader, return_exceptions=True)

    async def run(self):
        loop = asyncio.get_running_loop()
        current = asyncio.current_task()
        for sig in (signal.SIGTERM, signal.SIGINT):
            loop.add_signal_handler(sig, current.cancel)
        try:
            while not self.stopping:
                try:
                    from aichat import tasks
                    await self.api.call("POST", "/api/agent/heartbeat", {"adapter": "claude-sdk", "bridge_version": tasks.PLATFORM_VERSION, "guide_version": tasks.GUIDE_VERSION})
                    s = (await self.api.call("GET", "/api/agent/runtime"))["settings"]
                    self.jobs = {j for j in self.jobs if not j.done()}
                    if len(self.jobs) < s["max_concurrency"]:
                        response = await self.api.call("POST", "/api/agent/lease", params={"engine": "claude-sdk", "owner": self.owner, "profiles": "chat,delivery,memory"})
                        if response["lease"]:
                            self.jobs.add(asyncio.create_task(self.execute(response["lease"])))
                            continue
                except GatewayError as e:
                    if e.status in (401, 403):
                        return
                except (OSError, TimeoutError):
                    pass
                except Exception:
                    pass  # connectivity recovers; no fallback model/engine
                await asyncio.sleep(1)
        finally:
            for job in self.jobs:
                job.cancel()
            await asyncio.gather(*self.jobs, return_exceptions=True)
            await self.api.close()


def main():
    parser = argparse.ArgumentParser(description="SophosChat 服务端 Claude Agent SDK")
    parser.add_argument("--bootstrap-stdin", action="store_true", required=True)
    args = parser.parse_args()
    bootstrap = json.loads(sys.stdin.readline())
    if bootstrap.get("controller_pid"):
        from .watchdog import watch_parent
        watch_parent(bootstrap["controller_pid"])
    try:
        asyncio.run(AgentService(bootstrap["url"], bootstrap["credential"], bootstrap["state_dir"]).run())
    except (asyncio.CancelledError, KeyboardInterrupt):
        pass


if __name__ == "__main__":
    main()
